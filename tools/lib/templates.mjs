function listing({ heading, intro, filters, cards }) {
  const filterHtml = filters
    ? `\n      <div class="filters" role="group" aria-label="Filter projects">
        <button class="filter" type="button" data-filter="" aria-pressed="true">All</button>
${filters.map((f) => `        <button class="filter" type="button" data-filter="${esc(f.key)}" aria-pressed="false">${esc(f.label)}</button>`).join('\n')}
      </div>`
    : '';
  return `  <main class="listing container">
    <header class="listing__head reveal">
      <h1>${heading}</h1>
      <p>${intro}</p>${filterHtml}
    </header>

    <div class="grid">
${indent(cards.join('\n'), 6)}
    </div>
  </main>`;
}

