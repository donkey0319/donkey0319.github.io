// Indents generated HTML for readability — except inside <pre>, where every
// space is content (e.g. pasted shader code).
const indent = (html, n) => {
  const pad = ' '.repeat(n);
  let inPre = false;
  return html
    .split('\n')
    .map((l) => {
      const out = inPre ? l : l.trim() ? pad + l : '';
      if (/<pre[\s>]/.test(l)) inPre = true;
      if (l.includes('</pre>')) inPre = false;
      return out;
    })
    .join('\n');
};

