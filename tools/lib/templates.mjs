export function projectPage(p) {
  const hero = p.hero
    ? `
    <div class="project__hero">
${indent(renderMedia(p.hero, { poster: p.heroPoster, caption: p.heroCaption, loop: p.heroLoop, alt: p.title }), 6)}
    </div>`
    : '';
  const facts = p.facts.length
    ? `\n    <dl class="facts">\n${p.facts.map(([k, v]) => `      <div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join('\n')}\n    </dl>\n`
    : '';
  const what = p.whatIDid
    ? `\n    <section class="what-i-did">\n      <h2>What I did</h2>\n${indent(renderBody(p.whatIDid), 6)}\n    </section>\n`
    : `\n    <!-- TODO(victor): what I did -->\n    <!-- set what_i_did: in ${p.source} -->\n`;
  const links = p.links.length
    ? `\n    <p class="project__links">${p.links.map((l) => `<a href="${esc(l.url)}" target="_blank" rel="noopener">${esc(l.text)}</a>`).join(' · ')}</p>\n`
    : '';
  const main = `  <main class="project container container--narrow">
    <a class="back" href="/work/">← All work</a>
    <p class="project__kind">${esc(p.label)}</p>
    <h1>${esc(p.title)}</h1>
${hero}
${facts}${what}${links}
    <div class="project__body reveal">
${indent(renderBody(p.body), 6)}
    </div>
  </main>`;
  return layout({
    title: `${p.title} · Victor Lu`,
    ogTitle: p.title,
    description: p.description,
    url: projectUrl(p),
    ogType: 'article',
    current: null,
    main,
    source: p.source,
  });
}

export function sitemap(paths) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${paths.map((p) => `  <url><loc>${SITE_URL}${p}</loc></url>`).join('\n')}
</urlset>
`;
}
