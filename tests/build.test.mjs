import { test } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { ROOT } from './helpers.mjs';
import { buildSite, LEGACY } from '../tools/lib/build.mjs';

const out = buildSite({ contentDir: path.join(ROOT, 'tests/fixtures/content'), assetRoot: ROOT });
const page = (p) => {
  assert.ok(out.has(p), `missing ${p}`);
  return out.get(p);
};
const navOf = (html) => (html.match(/<ul class="nav__links">([\s\S]*?)<\/ul>/) || [])[1] || '';

test('builds every page, project page, redirect and the sitemap', () => {
  for (const p of [
    'index.html',
    'work/index.html',
    'games/index.html',
    'about/index.html',
    'projects/alpha/index.html',
    'projects/beta-game/index.html',
    'artwork/index.html',
    'sitemap.xml',
  ]) assert.ok(out.has(p), p);
  for (const old of Object.keys(LEGACY)) assert.ok(out.has(`${old}/index.html`), old);
});

test('every generated page says where it came from', () => {
  for (const [p, html] of out) {
    if (!p.endsWith('.html')) continue;
    assert.match(html, /^<!doctype html>\n<!-- Generated by tools\/site\.mjs from \S+ — edit that file, not this one\. -->/, p);
  }
  assert.match(page('projects/alpha/index.html'), /from content\/projects\/alpha\.md/);
});

test('work page: filters from site.md and labelled cards', () => {
  const html = page('work/index.html');
  const buttons = [...html.matchAll(/<button class="filter"[^>]*data-filter="([^"]*)"[^>]*>([^<]*)</g)].map((m) => [m[1], m[2]]);
  assert.deepEqual(buttons, [['', 'All'], ['shaders', 'Shaders'], ['environment', 'Environment Design']]);
  const cards = [...html.matchAll(/<article class="card reveal" data-categories="([^"]*)">\s*<a class="card__link" href="([^"]*)"/g)].map((m) => [m[2], m[1]]);
  assert.deepEqual(cards, [['/projects/alpha/', 'shaders environment'], ['/projects/beta-game/', 'environment']]);
  assert.match(html, /<video src="\/assets\/videos\/painterly\/painterly\.mp4" poster="\/assets\/images\/painterly\/painterly\.png" autoplay muted loop playsinline preload="metadata"><\/video>/);
  assert.match(html, /<ul class="tags"><li>UE5<\/li><li>Shader<\/li><\/ul>/);
  assert.match(html, /<script src="\/assets\/js\/work-filter\.js"><\/script>/);
});

test('games page: only games, no labels', () => {
  const html = page('games/index.html');
  const hrefs = [...html.matchAll(/class="card__link" href="([^"]*)"/g)].map((m) => m[1]);
  assert.deepEqual(hrefs, ['/projects/beta-game/']);
  assert.doesNotMatch(html, /data-categories/);
});

test('cards with no summary keep the TODO comment and no empty tag list', () => {
  const html = page('games/index.html');
  assert.match(html, /<!-- TODO\(victor\): what I did/);
  assert.doesNotMatch(html, /<p class="card__what">/);
  assert.doesNotMatch(html, /<ul class="tags">/);
});

test('home: highlight tiles in order with poster and video', () => {
  const html = page('index.html');
  const tiles = [...html.matchAll(/<a class="level[^"]*" href="([^"]*)"([^>]*)>/g)];
  assert.equal(tiles.length, 1);
  assert.equal(tiles[0][1], '/projects/alpha/');
  assert.match(tiles[0][2], /data-video="\/assets\/videos\/painterly\/painterly\.mp4"/);
  assert.match(tiles[0][2], /data-poster="\/assets\/images\/painterly\/painterly\.png"/);
  assert.match(html, /<a class="level is-active"/);
  assert.match(html, /<video class="title__video" src="\/assets\/videos\/painterly\/painterly\.mp4" poster="\/assets\/images\/painterly\/painterly\.png"/);
  assert.match(html, /<p class="title__role">Technical Artist<\/p>/);
  assert.match(html, /'#games':\s*'\/games\/'/);
});

test('project page: back link, label, hero, facts, what I did, body', () => {
  const html = page('projects/alpha/index.html');
  assert.match(html, /<a class="back" href="\/work\/">← All work<\/a>/);
  assert.match(html, /<p class="project__kind">Shaders<\/p>\s*<h1>Alpha Piece<\/h1>/);
  assert.match(html, /<div class="project__hero">\s*<video controls playsinline preload="metadata" poster="\/assets\/images\/pekora\/faceshadow-poster\.jpg">/);
  assert.match(html, /<p class="caption">Hero caption here\.<\/p>\s*<\/div>/);
  assert.deepEqual([...html.matchAll(/<dt>([^<]*)<\/dt><dd>([^<]*)<\/dd>/g)].map((m) => [m[1], m[2]]), [['Tools', 'UE5'], ['Role', 'Solo']]);
  assert.match(html, /<section class="what-i-did">\s*<h2>What I did<\/h2>\s*<p>I built the alpha shader\.<\/p>/);
  assert.match(html, /<div class="project__body reveal">[\s\S]*<h3 id="first-section">First Section<\/h3>[\s\S]*<p class="caption">A clip<\/p>/);
});

test('project page without facts or what-I-did', () => {
  const html = page('projects/beta-game/index.html');
  assert.doesNotMatch(html, /<dl class="facts">/);
  assert.match(html, /<!-- TODO\(victor\): what I did -->/);
  assert.match(html, /<div class="embed"><iframe src="https:\/\/www\.youtube-nocookie\.com\/embed\/KlP4yi8pVPE"/);
  assert.match(html, /<p class="project__links"><a href="https:\/\/example\.com\/play" target="_blank" rel="noopener">Play on itch\.io →<\/a><\/p>/);
});

test('nav is Home, Work, Games, About with the right page marked', () => {
  const current = { 'index.html': '/', 'work/index.html': '/work/', 'games/index.html': '/games/', 'about/index.html': '/about/', 'projects/alpha/index.html': null };
  for (const [p, cur] of Object.entries(current)) {
    const nav = navOf(page(p));
    assert.deepEqual([...nav.matchAll(/href="([^"]*)"/g)].map((m) => m[1]), ['/', '/work/', '/games/', '/about/'], p);
    assert.deepEqual([...nav.matchAll(/href="([^"]*)" aria-current="page"/g)].map((m) => m[1]), cur ? [cur] : [], p);
  }
});

test('about renders site.md text with orange bold', () => {
  assert.match(page('about/index.html'), /<strong class="accent">Technical Artist<\/strong>/);
});

test('redirect stubs point at the new pages', () => {
  assert.match(page('artwork/index.html'), /content="0; url=\/work\/"/);
  const [old, slug] = Object.entries(LEGACY)[0];
  assert.match(page(`${old}/index.html`), /content="0; url=\/(projects\/[a-z0-9-]+|work)\/"/);
  assert.ok(slug);
});

test('sitemap lists pages, projects and the old blog', () => {
  const xml = page('sitemap.xml');
  for (const p of ['/', '/work/', '/games/', '/about/', '/projects/alpha/', '/projects/beta-game/', '/posts/', '/welcome-to-my-site/']) {
    assert.ok(xml.includes(`<loc>https://donkey0319.github.io${p}</loc>`), p);
  }
  assert.doesNotMatch(xml, /\/artwork\//);
});
